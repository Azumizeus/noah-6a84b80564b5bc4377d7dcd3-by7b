export const translations: Record<Lang, Dict> = { fr, en };

function getNode(lang: Lang, key: string): string | undefined {
  const path = key.split('.');
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  let node: any = translations[lang];
  for (const p of path) {
    if (node == null) return undefined;
    node = node[p];
  }
  return typeof node === 'string' ? node : undefined;
}

/** Traduit `key` (dot-path, ex: "nav.dashboard") pour `lang`, avec interpolation {{var}}. */
export function translate(lang: Lang, key: string, params?: Record<string, string | number>): string {
  let result = getNode(lang, key) ?? getNode('fr', key) ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      result = result.split(`{{${k}}}`).join(String(v));
    }
  }
  return result;
}